def key(c):
    return (c['kind'], tuple(c['values']), c.get('scope'), c.get('negate', False))


def main(path=None):
    path = path or os.path.join(HERE, 'passages_j4.json')
    with open(path, encoding='utf-8') as f:
        data = json.load(f)
    done = skipped = 0
    for p in data:
        if p['parse'] != 'unparsed':
            if p['id'] in DEC:
                skipped += 1
            continue
        d = DEC.get(p['id'])
        if d is None:
            if p['id'] in TYPES:
                p['decode_type'] = TYPES[p['id']]
            continue
        keep = [c for c in p['conds'] if c['kind'] != 'raw']      # 모드 A: raw만 빼고 지정한 조건을 더한다
        have = {key(c) for c in keep}
        keep += [c for c in d['conds'] if key(c) not in have]
        p['decoded_from'] = p.get('reason')
        p.pop('reason', None)
        p['decode_type'] = TYPES.get(p['id'])
        p['conds'] = keep
        p['parse'] = 'manual'
        old = p.get('note')
        s = 'O25 해독: %s. 근거 %s %s행 「%s」' % (d['why'], p['file'], p['line'], p['text'])
        p['note'] = (old + ' / ' + s) if old else s
        done += 1
    tmp = path + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    os.replace(tmp, path)
    print('권4: 옮긴 구절 %d, 이미 처리됨 %d' % (done, skipped))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else None)
