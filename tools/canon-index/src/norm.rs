fn map() -> &'static std::collections::HashMap<char, char> {
    use std::sync::OnceLock;
    static M: OnceLock<std::collections::HashMap<char, char>> = OnceLock::new();
    M.get_or_init(|| {
        let mut m = std::collections::HashMap::new();
        for (a, b) in SIMPLIFIED_TABLE.iter().chain(EXTRA_TABLE.iter()).chain(SPEC_TABLE.iter()) {
            m.insert(*a, *b);
        }
        m
    })
}

pub fn map_char(c: char) -> char {
    map().get(&c).copied().unwrap_or(c)
}

pub fn normalize(s: &str) -> String {
    s.chars().map(map_char).collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;
    fn all_tables() -> impl Iterator<Item = &'static (char, char)> {
        SPEC_TABLE.iter().chain(EXTRA_TABLE.iter()).chain(SIMPLIFIED_TABLE.iter())
    }

    #[test]
    fn length_preserved() {
        let s = "嵗歳𡻕㐫𤎉亷㑹庙冨㣲夀𢙣竒羙䕃湏逺觧隂啇𦂳盖荣宫徳凾数䘮刼闗𬧙灾禄杀迁夲 紫微斗数ABC，。";
        let n = normalize(s);
        assert_eq!(s.chars().count(), n.chars().count());
        assert!(n.starts_with("歲歲歲凶廉廉會廟富微壽惡奇美蔭須遠解陰商緊蓋榮宮德函數喪劫關蹭災祿殺遷本"));
        assert!(n.ends_with(" 紫微斗數ABC，。"));
    }

    #[test]
    fn table_is_one_to_one_and_stable() {
        let mut seen = HashSet::new();
        for (a, _) in all_tables() {
            // 같은 키가 겹쳐도 같은 값이어야 한다
            let _ = seen.insert(*a);
        }
        for (a, b) in all_tables() {
            assert_eq!(map_char(*a), map_char(*a));
            // 값은 다시 변환되지 않아야 한다(멱등)
            assert_eq!(map_char(*b), *b, "target {b} is itself a key");
            let found: Vec<char> = all_tables()
                .filter(|(k, _)| k == a)
                .map(|(_, v)| *v)
                .collect();
            assert!(found.iter().all(|v| v == &found[0]), "key {a} has conflicting targets");
        }
        let s = "嵗隂数";
        assert_eq!(normalize(&normalize(s)), normalize(s));
    }

    #[test]
    fn simplified_to_traditional() {
        let n = normalize("岁运灾杀禄宫财迁 夫妻 阳机");
        assert_eq!(n, "歲運災殺祿宮財遷 夫妻 陽機");
        assert_eq!("岁运灾杀禄宫财迁".chars().count(), normalize("岁运灾杀禄宫财迁").chars().count());
        assert_eq!(normalize("三台"), "三台");
    }
}
